export const DemoAnimationsMorphHills = () => {
  const containerRef = useRef<HTMLDivElement | null>(null);

  const [speed, setSpeed] = useState<number>(40);

  const [isPlaying, setIsPlaying] = useState<boolean>(false);

  const onSpeedChange = (value: number) => {
    setSpeed(value);
  };

  useEffect(() => {
    if (!containerRef.current) {
      return;
    }
    containerRef.current
      .querySelector("animate")
      ?.setAttribute("dur", `${speed}s`);
  }, [speed]);

  const onPlay = () => {
    setIsPlaying(true);
  };
  const onPause = () => {
    setIsPlaying(false);
  };
  const onReset = () => {
    setIsPlaying(false);
  };

  return (
    <DemoAnimation
      ref={containerRef}
      playbackControl={{
        isPlaying,
        speedMin: 0,
        speedMax: 80,
        speed,
        onSpeedChange,
        onPlay,
        onPause,
        onReset,
      }}
    >
      <HillsSvgStyling viewBox="0 0 50 50">
        <rect x="0" y="0" width="50" height="50" />{" "}
        <path d={steam1} className="hill-back">
          <animate
            attributeName="d"
            dur={`${speed}s`}
            repeatCount="indefinite"
            values={`${steam1};${steam2};${steam1}`}
          />
        </path>
        <path d={steam3} className="hill-front">
          <animate
            attributeName="d"
            dur={`${speed}s`}
            repeatCount="indefinite"
            values={`${steam3};${steam4};${steam3}`}
          />
        </path>
      </HillsSvgStyling>
    </DemoAnimation>
  );
};
